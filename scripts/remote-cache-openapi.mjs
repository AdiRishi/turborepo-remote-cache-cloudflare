import { mkdir, readFile, rename, rm, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import openapiTS, { astToString } from 'openapi-typescript';
import { format } from 'oxfmt';
import ts from 'typescript';

const sourceUrl = 'https://turborepo.dev/api/remote-cache-spec';
const projectRoot = fileURLToPath(new URL('../', import.meta.url));
const specPath = fileURLToPath(new URL('../openapi/turborepo-remote-cache.json', import.meta.url));
const generatedPath = fileURLToPath(
  new URL('../src/protocol/remote-cache/generated.ts', import.meta.url),
);

const generatedHeader = `/**
 * Generated from openapi/turborepo-remote-cache.json by pnpm api:generate.
 * Source: ${sourceUrl}
 *
 * Do not edit this file directly.
 */

`;

const httpMethods = ['get', 'put', 'post', 'delete', 'options', 'head', 'patch', 'trace'];

function operationEntries(document) {
  const entries = [];

  for (const [path, pathItem] of Object.entries(document.paths)) {
    if (!pathItem || typeof pathItem !== 'object' || Array.isArray(pathItem)) continue;

    for (const method of httpMethods) {
      const operation = pathItem[method];
      if (!operation) continue;
      entries.push({ method, operationId: operation.operationId, path });
    }
  }

  return entries;
}

function validateLocalReferences(document) {
  const externalReferences = [];
  const values = [document];

  while (values.length > 0) {
    const value = values.pop();
    if (Array.isArray(value)) {
      values.push(...value);
    } else if (value && typeof value === 'object') {
      if (typeof value.$ref === 'string' && !value.$ref.startsWith('#/')) {
        externalReferences.push(value.$ref);
      }
      values.push(...Object.values(value));
    }
  }

  if (externalReferences.length > 0) {
    throw new Error(
      `The pinned specification must be self-contained; external $ref values: ${externalReferences.join(', ')}.`,
    );
  }
}

function validateDocument(document) {
  if (!document || typeof document !== 'object' || Array.isArray(document)) {
    throw new Error('The remote cache specification must be a JSON object.');
  }

  if (typeof document.openapi !== 'string' || !document.openapi.startsWith('3.')) {
    throw new Error(`Expected an OpenAPI 3 document, received ${String(document.openapi)}.`);
  }

  if (!document.paths || typeof document.paths !== 'object' || Array.isArray(document.paths)) {
    throw new Error('The remote cache specification does not define any paths.');
  }

  validateLocalReferences(document);

  const operations = operationEntries(document);
  for (const operation of operations) {
    if (typeof operation.operationId !== 'string' || operation.operationId.length === 0) {
      throw new Error(
        `Every operation must have an operationId; one is missing for ${operation.method.toUpperCase()} ${operation.path}.`,
      );
    }
  }

  if (operations.length === 0) {
    throw new Error('The remote cache specification does not define any operations.');
  }

  const operationIds = operations.map(({ operationId }) => operationId);
  const duplicateOperationIds = operationIds.filter(
    (operationId, index) => operationIds.indexOf(operationId) !== index,
  );
  if (duplicateOperationIds.length > 0) {
    throw new Error(
      `Duplicate operationId values: ${[...new Set(duplicateOperationIds)].join(', ')}.`,
    );
  }
}

function operationManifest(document) {
  const entries = operationEntries(document).toSorted((left, right) =>
    left.operationId < right.operationId ? -1 : left.operationId > right.operationId ? 1 : 0,
  );
  const manifest = Object.fromEntries(
    entries.map(({ method, operationId, path }) => [operationId, { method, path }]),
  );

  return `export const remoteCacheOperations = ${JSON.stringify(manifest, null, 2)} as const;\n\n`;
}

const normalizeLineEndings = (contents) => contents.replace(/\r\n?/g, '\n');

async function formatContents(fileName, contents) {
  const result = await format(fileName, contents, { singleQuote: true });
  if (result.errors.length > 0) {
    throw new Error(
      `Unable to format ${fileName}: ${result.errors.map((error) => error.message).join('; ')}`,
    );
  }
  return result.code;
}

async function canonicalJson(document) {
  return formatContents(specPath, JSON.stringify(document, null, 2));
}

function binaryStreamType() {
  return ts.factory.createTypeReferenceNode('ReadableStream', [
    ts.factory.createTypeReferenceNode('Uint8Array'),
  ]);
}

async function generateContract(document) {
  const ast = await openapiTS(document, {
    alphabetize: true,
    transform(schema) {
      if (schema.type === 'string' && schema.format === 'binary') {
        return binaryStreamType();
      }
      return undefined;
    },
  });

  return formatContents(
    generatedPath,
    `${generatedHeader}${operationManifest(document)}${astToString(ast)}`,
  );
}

async function readSnapshot() {
  let contents;
  try {
    contents = await readFile(specPath, 'utf8');
  } catch (error) {
    if (error && typeof error === 'object' && error.code === 'ENOENT') {
      throw new Error('The pinned specification is missing. Run pnpm api:sync first.', {
        cause: error,
      });
    }
    throw error;
  }

  const document = JSON.parse(contents);
  validateDocument(document);
  return { contents, document };
}

async function sync() {
  const response = await fetch(sourceUrl, {
    headers: { accept: 'application/json' },
    redirect: 'follow',
  });
  if (!response.ok) {
    throw new Error(`Unable to download ${sourceUrl}: ${response.status} ${response.statusText}.`);
  }

  const document = await response.json();
  validateDocument(document);

  await mkdir(new URL('../openapi/', import.meta.url), { recursive: true });
  const temporaryPath = `${specPath}.${process.pid}.tmp`;
  try {
    await writeFile(temporaryPath, await canonicalJson(document), 'utf8');
    await rename(temporaryPath, specPath);
  } finally {
    await rm(temporaryPath, { force: true });
  }

  console.log(`Updated ${specPath.slice(projectRoot.length)} from ${sourceUrl}.`);
  console.log('Review the specification diff, then run pnpm api:generate.');
}

async function generate() {
  const { document } = await readSnapshot();
  const generated = await generateContract(document);

  await mkdir(new URL('../src/protocol/remote-cache/', import.meta.url), { recursive: true });
  await writeFile(generatedPath, generated, 'utf8');
  console.log(`Generated ${generatedPath.slice(projectRoot.length)}.`);
}

async function check() {
  const { contents, document } = await readSnapshot();
  if (normalizeLineEndings(contents) !== (await canonicalJson(document))) {
    throw new Error('The pinned specification is not canonical JSON. Run pnpm api:sync.');
  }

  const expected = await generateContract(document);
  let actual;
  try {
    actual = await readFile(generatedPath, 'utf8');
  } catch (error) {
    if (error && typeof error === 'object' && error.code === 'ENOENT') {
      throw new Error('The generated contract is missing. Run pnpm api:generate.', {
        cause: error,
      });
    }
    throw error;
  }

  if (normalizeLineEndings(actual) !== expected) {
    throw new Error(
      'The generated contract is stale. Run pnpm api:generate and commit the result.',
    );
  }

  console.log('The pinned specification and generated contract are up to date.');
}

const command = process.argv[2];
try {
  if (command === 'sync') {
    await sync();
  } else if (command === 'generate') {
    await generate();
  } else if (command === 'check') {
    await check();
  } else {
    throw new Error('Usage: node scripts/remote-cache-openapi.mjs <sync|generate|check>');
  }
} catch (error) {
  console.error(error instanceof Error ? error.message : error);
  process.exitCode = 1;
}
